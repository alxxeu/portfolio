(() => {
  "use strict";

  const qs = (selector, root = document) => root.querySelector(selector);
  const qsa = (selector, root = document) => [...root.querySelectorAll(selector)];

  // --- Story carousels (Instagram Stories-style viewer inside modals) ---
  const initStoryCarousels = (root = document) => {
    qsa('.story-carousel', root).forEach((carousel) => {
      if (carousel.dataset.carouselInit) return;
      carousel.dataset.carouselInit = 'true';
      carousel.dataset.index = '0';

      const track = qs('.story-track', carousel);
      const slides = qsa('.story-slide', carousel);
      const segs = qsa('.story-seg', carousel);
      const prevBtn = qs('.story-arrow.prev', carousel);
      const nextBtn = qs('.story-arrow.next', carousel);
      const prevTap = qs('.story-tap.prev', carousel);
      const nextTap = qs('.story-tap.next', carousel);
      const total = slides.length;
      if (!track || !total) return;

      const render = () => {
        const index = Number(carousel.dataset.index || 0);
        track.style.transform = `translateX(-${index * 100}%)`;
        segs.forEach((seg, i) => seg.classList.toggle('is-filled', i <= index));
        slides.forEach((slide, i) => {
          if (slide.tagName !== 'VIDEO') return;
          if (i === index && carousel._storyActive) {
            slide.play().catch(() => {});
          } else {
            slide.pause();
            if (i !== index) slide.currentTime = 0;
          }
        });
        if (prevBtn) prevBtn.disabled = index === 0;
        if (nextBtn) nextBtn.disabled = index === total - 1;
      };

      const go = (delta) => {
        const index = Number(carousel.dataset.index || 0);
        const next = index + delta;
        if (next < 0 || next >= total) return;
        carousel.dataset.index = String(next);
        render();
      };

      if (prevBtn) prevBtn.addEventListener('click', (e) => { e.stopPropagation(); go(-1); });
      if (nextBtn) nextBtn.addEventListener('click', (e) => { e.stopPropagation(); go(1); });
      if (prevTap) prevTap.addEventListener('click', () => go(-1));
      if (nextTap) nextTap.addEventListener('click', () => go(1));

      let touchStartX = 0;
      carousel.addEventListener('touchstart', (e) => {
        touchStartX = e.touches[0].clientX;
      }, { passive: true });
      carousel.addEventListener('touchend', (e) => {
        const dx = e.changedTouches[0].clientX - touchStartX;
        if (Math.abs(dx) > 40) go(dx < 0 ? 1 : -1);
      }, { passive: true });

      carousel._storyReset = () => {
        carousel.dataset.index = '0';
        render();
      };

      // Video slides: play only the visible one while its modal is open,
      // tap the video to pause/resume, one button toggles sound for all.
      const videos = slides.filter((s) => s.tagName === 'VIDEO');
      if (videos.length) {
        carousel._storySetActive = (on) => {
          carousel._storyActive = on;
          if (!on) {
            videos.forEach((v) => { v.muted = true; });
            const btn = qs('.story-sound', carousel);
            if (btn) btn.classList.remove('is-on');
          }
          render();
        };
        videos.forEach((v) => v.addEventListener('click', () => {
          if (v.paused) v.play().catch(() => {}); else v.pause();
        }));
        const soundBtn = qs('.story-sound', carousel);
        if (soundBtn) {
          soundBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const unmute = videos[0].muted;
            videos.forEach((v) => { v.muted = !unmute; });
            soundBtn.classList.toggle('is-on', unmute);
          });
        }
      }

      // Shape the carousel to fit the actual slide format (portrait, square,
      // landscape, anything) instead of assuming a fixed 9:16 Stories ratio.
      const BOUND_W = 480; // widest a carousel is allowed to get
      const BOUND_H = 500; // tallest a carousel is allowed to get
      const fitToImage = (img) => {
        const w = img.naturalWidth || img.videoWidth;
        const h = img.naturalHeight || img.videoHeight;
        if (!w || !h) return;
        const ratio = w / h;
        const widthIfHeightBound = BOUND_H * ratio;
        const finalWidth = Math.min(widthIfHeightBound, BOUND_W);
        carousel.style.aspectRatio = `${w} / ${h}`;
        carousel.style.maxWidth = `${Math.round(finalWidth)}px`;
      };

      const firstSlide = slides[0];
      if (firstSlide) {
        if (firstSlide.tagName === 'VIDEO') {
          if (firstSlide.readyState >= 1) fitToImage(firstSlide);
          else firstSlide.addEventListener('loadedmetadata', () => fitToImage(firstSlide), { once: true });
        } else if (firstSlide.complete && firstSlide.naturalWidth) {
          fitToImage(firstSlide);
        } else {
          firstSlide.addEventListener('load', () => fitToImage(firstSlide), { once: true });
        }
      }

      render();
    });
  };

  initStoryCarousels();

  // --- Modals (e.g. "More about Thoughts") ---
  const openModal = (modal) => {
    modal.classList.add('is-open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';

    const scrollArea = qs('[data-modal-scroll]', modal);
    const header = qs('.modal-header', modal);
    if (scrollArea) scrollArea.scrollTop = 0;
    if (header) header.classList.remove('is-scrolled');

    qsa('.story-carousel', modal).forEach((carousel) => {
      if (carousel._storyReset) carousel._storyReset();
      if (carousel._storySetActive) carousel._storySetActive(true);
    });
    qsa('video.modal-video', modal).forEach((v) => {
      v.currentTime = 0;
      v.play().catch(() => {});
    });
  };

  const closeModal = (modal) => {
    modal.classList.remove('is-open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
    qsa('.story-carousel', modal).forEach((carousel) => {
      if (carousel._storySetActive) carousel._storySetActive(false);
    });
    qsa('video.modal-video', modal).forEach((v) => v.pause());
  };

  qsa('[data-modal-target]').forEach((btn) => {
    btn.addEventListener('click', () => {
      const modal = document.getElementById(btn.dataset.modalTarget);
      if (modal) openModal(modal);
    });
  });

  qsa('.modal-overlay').forEach((overlay) => {
    overlay.addEventListener('click', (e) => {
      if (e.target === overlay) closeModal(overlay);
    });
    qsa('[data-modal-close]', overlay).forEach((btn) => {
      btn.addEventListener('click', () => closeModal(overlay));
    });

    const scrollArea = qs('[data-modal-scroll]', overlay);
    const header = qs('.modal-header', overlay);
    if (scrollArea && header) {
      scrollArea.addEventListener('scroll', () => {
        header.classList.toggle('is-scrolled', scrollArea.scrollTop > 8);
      }, { passive: true });
    }
  });

  document.addEventListener('keydown', (e) => {
    if (e.key !== 'Escape') return;
    qsa('.modal-overlay.is-open').forEach((overlay) => closeModal(overlay));
  });

  // --- Language switch (EN / RU) ---
  const LANG_KEY = 'site-lang';
  let currentLang = 'en';

  const applyLanguage = (lang) => {
    currentLang = lang;
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

    qsa('[data-i18n]').forEach((el) => {
      const value = dict[el.dataset.i18n];
      if (value === undefined) return;
      if (el.tagName === 'TEXTAREA' || el.tagName === 'INPUT') el.value = value;
      else el.textContent = value;
    });

    qsa('[data-i18n-placeholder]').forEach((el) => {
      const value = dict[el.dataset.i18nPlaceholder];
      if (value !== undefined) el.setAttribute('placeholder', value);
    });

    qsa('[data-i18n-aria]').forEach((el) => {
      const value = dict[el.dataset.i18nAria];
      if (value !== undefined) el.setAttribute('aria-label', value);
    });

    if (dict['meta.title']) document.title = dict['meta.title'];
    const metaDesc = qs('meta[name="description"]');
    if (metaDesc && dict['meta.description']) metaDesc.setAttribute('content', dict['meta.description']);

    document.documentElement.setAttribute('lang', lang);

    qsa('.lang-btn').forEach((btn) => {
      btn.classList.toggle('is-active', btn.dataset.lang === lang);
    });

    try { localStorage.setItem(LANG_KEY, lang); } catch (err) { /* storage unavailable */ }
  };

  qsa('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => applyLanguage(btn.dataset.lang));
  });

  let initialLang = 'en';
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored === 'en' || stored === 'ru') initialLang = stored;
  } catch (err) { /* storage unavailable */ }

  applyLanguage(initialLang);

})();
